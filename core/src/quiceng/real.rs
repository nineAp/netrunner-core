//! Настоящий QUIC до собственного домена узла (`DecoyMode::SelfHosted`) —
//! **не реализовано в этой правке**, только зафиксированная точка расширения.
//!
//! ## Почему не мимикрия здесь
//!
//! Когда decoy — не одолженный чужой сайт, а домен и сертификат самого узла
//! (см. [`crate::tlseng::decoy`] за тем, откуда взялось это различие для
//! TCP-ноги), изображать QUIC незачем: можно говорить настоящим протоколом
//! до настоящего HTTP/3-сайта узла с настоящим сертификатом. Активный зонд,
//! умеющий довести реальный QUIC-хендшейк до конца, получает ЧЕСТНЫЙ ответ,
//! а не мимикрию, которая рано или поздно проваливается на глубокой
//! проверке (см. [`super::initial`] за тем, где именно проваливается наша).
//!
//! ## Почему это не реализовано сейчас, а не "забыто"
//!
//! Реальный клиент QUIC — это `quinn`/`rustls` как прямая зависимость
//! `core` (сейчас `quinn` есть только в `masque-edge`, отдельном бинаре без
//! связи с этим крейтом) под тем же `cfg(not(target_arch = "wasm32"))`,
//! что и остальной [`crate::net::connection`] (см. `core/Cargo.toml`).
//! Дальше нужно решить вопросы, которые этот крейт сам по себе не знает:
//!
//! - какой ALPN и какое расширение (`DATAGRAM`, RFC 9221) реально
//!   поддерживает веб-сервер, который сейчас обслуживает витрину узла —
//!   это инфраструктура развёртывания, не код этого репозитория;
//! - путь до сертификата/ключа этого сервера, чтобы `quinn::Endpoint`
//!   мог их прочитать;
//! - как трафик [`crate::nrxp::datagram`] едет поверх настоящего QUIC —
//!   вероятно, как `DATAGRAM`-фреймы (RFC 9221), но это нужно сверить с
//!   тем, что реально включено на сервере.
//!
//! Дописывать эту интеграцию, не имея возможности её проверить против
//! реального развёртывания узла, значило бы отправить непроверяемый код в
//! ядро VPN — поэтому здесь только типизированная точка расширения.
//! [`QuicMode::for_decoy`](super::QuicMode::for_decoy) уже выбирает
//! [`super::QuicMode::Real`] для `DecoyMode::SelfHosted`; когда этот модуль
//! будет реализован, месту, откуда сегодня возвращается эта заглушка,
//! останется просто дать настоящую реализацию.

/// Что понадобится вызывающему коду, чтобы поднять настоящее QUIC-соединение
/// до собственного домена узла. Поля — минимальный набор, видимый уже сейчас;
/// сама реализация (см. докстринг модуля) — следующий шаг.
pub(crate) struct RealQuicTarget {
    /// Домен узла — он же ALPN/SNI настоящего TLS в QUIC, он же CN сертификата.
    pub(crate) domain: String,
    pub(crate) addr: std::net::SocketAddr,
}

/// Ошибка "эта возможность ещё не реализована" — отдельный тип, а не
/// `unimplemented!()`: паника здесь была бы неверной семантикой (это не баг,
/// а известный, документированный пробел), а вызывающий код должен суметь
/// откатиться на мимикрию или на TCP-фолбэк, а не уронить процесс.
#[derive(Debug)]
pub(crate) struct NotYetImplemented;

pub(crate) fn dial(_target: &RealQuicTarget) -> Result<(), NotYetImplemented> {
    Err(NotYetImplemented)
}
