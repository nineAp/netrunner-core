//! # Движок WebRTC-маскировки (`webrtceng`)
//!
//! Тот же принцип, что [`crate::quiceng`] и, до него, [`crate::tlseng`]: наш
//! собственный протокол ([`crate::nrxp::datagram`]) поверх формы чужого —
//! здесь RTP/SRTP (RFC 3550/3711), а не QUIC.
//!
//! ## Состав блока
//!
//! | Файл            | Ответственность                                                      |
//! |------------------|----------------------------------------------------------------------|
//! | [`fingerprint`]  | [`WebrtcProfile`] — payload type, частота дискретизации, шаг таймстампа. |
//! | [`rtp`]          | [`rtp::WebrtcTx`]/[`rtp::WebrtcRx`] — RTP-заголовок + AEAD с заголовком как AAD. |
//!
//! ## Почему здесь нет `WebrtcMode::Real`
//!
//! У QUIC-ноги ([`crate::quiceng::QuicMode`]) есть законный "настоящий" режим,
//! потому что HTTP/3-сайт можно реально размещать на своём домене со своим
//! сертификатом — ровно та же логика, что уже различает `DecoyMode::Relay`
//! и `DecoyMode::SelfHosted` для TCP. У WebRTC нет аналога "домен+сертификат,
//! которым узел владеет": участие в настоящем звонке требует настоящего
//! удалённого собеседника, которого нет и неоткуда взять. Поэтому
//! `webrtceng` — только мимикрия, без выбора режима.
//!
//! ## Чего здесь намеренно нет
//!
//! Полного ICE/STUN/DTLS сценария установки звонка (см.
//! `docs/UDP_LEG_RESEARCH.md` §5.4, открытый вопрос №3) и мимикрии временной
//! структуры трафика — всплесков на ключевых кадрах, соотношения размеров
//! пакетов настоящего видео/аудио (см. тот же документ, раздел про мимикрию
//! всплесков — открытый вопрос, а не реализация). Здесь — только форма
//! отдельного пакета и его крипто-привязка к заголовку.

mod fingerprint;
mod rtp;

pub(crate) use fingerprint::WebrtcProfile;
pub(crate) use rtp::{WebrtcRx, WebrtcTx};
